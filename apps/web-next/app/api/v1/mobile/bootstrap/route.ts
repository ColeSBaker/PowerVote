import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import path from "node:path";

import { NextResponse } from "next/server";

import { resolveCdnUrl } from "@/lib/server/cdn-manifest";
import { buildMobileBootstrapResponse, buildMobileCacheHeaders } from "@/lib/server/mobile-api";
import { resolveStaticArtifactsDirectory } from "@/lib/server/paths";
import { buildDiagnosticsHeaders } from "@/lib/server/response-diagnostics";
import { formatServerTiming } from "@/lib/server/server-timing";
import { errorResponse } from "@/lib/server/errors";

export async function GET(request: Request) {
  // Redirect to CDN when available — client downloads directly from R2 with immutable cache headers.
  const cdnUrl = resolveCdnUrl("mobile-bootstrap.json");
  if (cdnUrl) {
    return new Response(null, {
      status: 302,
      headers: {
        Location: cdnUrl,
        "Cache-Control": "public, max-age=300, stale-while-revalidate=86400",
        "X-CDN-Redirect": "1",
      },
    });
  }

  // Serve pre-computed static artifact when available (generated by daily ETL)
  const staticDir = resolveStaticArtifactsDirectory();
  if (staticDir) {
    const staticPath = path.join(staticDir, "mobile-bootstrap.json");
    if (existsSync(staticPath)) {
      try {
        const raw = await readFile(staticPath, "utf-8");
        const payload = JSON.parse(raw) as Awaited<ReturnType<typeof buildMobileBootstrapResponse>>;
        return new Response(raw, {
          status: 200,
          headers: {
            "Content-Type": "application/json",
            ...buildMobileCacheHeaders(payload),
            "X-Static-Artifact": "1",
          },
        });
      } catch {
        // Fall through to dynamic generation
      }
    }
  }

  // Dynamic fallback: compute from data files at request time
  try {
    let serverTimingHeader = "";
    const payload = await buildMobileBootstrapResponse((timing) => {
      serverTimingHeader = formatServerTiming([
        { name: "load", dur: timing.loadMs },
        { name: "build", dur: timing.buildMs },
        { name: "schema", dur: timing.schemaMs },
        { name: "total", dur: timing.totalMs },
      ]);
    });
    return NextResponse.json(payload, {
      status: 200,
      headers: {
        ...buildMobileCacheHeaders(payload),
        ...buildDiagnosticsHeaders(serverTimingHeader, request),
      },
    });
  } catch (error) {
    return errorResponse(error);
  }
}
